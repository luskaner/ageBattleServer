package main

// The generator is the part that has to be trustworthy for a reason the harness
// is not: the harness decides whether a difference matters, and the generator
// only decides whether a capture gets a test at all. A generator that silently
// skips a capture, or that overwrites a committed one, loses a run that cannot
// be repeated, so both are tested here rather than trusted.

import (
	"go/format"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

func formatSource(path string) ([]byte, error) {
	src, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	return format.Source(src)
}

// writeCaptureDir lays out a minimal capture: a metadata.json is what makes a
// directory a capture as far as the generator is concerned.
func writeCaptureDir(t *testing.T, root, name string) string {
	t.Helper()
	dir := filepath.Join(root, name)
	if err := os.MkdirAll(dir, 0o755); err != nil {
		t.Fatalf("mkdir %s: %v", dir, err)
	}
	body := `{"format_version":1,"commit":"abc","primary":{"writer":"original"},"secondary":{"writer":"ours"},` +
		`"primary_args":["-bsPort","14001"],"secondary_args":["-bsPort","15001"]}`
	if err := os.WriteFile(filepath.Join(dir, "metadata.json"), []byte(body+"\n"), 0o644); err != nil {
		t.Fatalf("write metadata.json: %v", err)
	}
	for _, f := range []string{"main.log", "secondary.log"} {
		if err := os.WriteFile(filepath.Join(dir, f), []byte("timestamp,src_host\n"), 0o644); err != nil {
			t.Fatalf("write %s: %v", f, err)
		}
	}
	return dir
}

// TestRunGeneratesATestPerCapture: the promise of the whole tool. Dropping a
// directory in produces a test that runs it, and the test carries no knowledge
// of the capture, because everything it needs is in the directory.
func TestRunGeneratesATestPerCapture(t *testing.T) {
	caps := t.TempDir()
	sim := t.TempDir()
	first := "2026-09-28_040213_56c1309"
	second := "2026-09-28_050000_deadbee"
	writeCaptureDir(t, caps, first)
	writeCaptureDir(t, caps, second)

	if err := run([]string{caps}, sim, false); err != nil {
		t.Fatalf("run: %v", err)
	}
	for _, name := range []string{first, second} {
		if _, err := os.Stat(filepath.Join(sim, testFileName(name))); err != nil {
			t.Errorf("%s was not generated: %v", name, err)
		}
		// The capture itself has to be readable from the sim package, or
		// `go test` cannot open it.
		if _, err := os.Stat(filepath.Join(sim, testDataDirName, name, "metadata.json")); err != nil {
			t.Errorf("the capture was not installed under testdata: %v", err)
		}
	}
	// The proxy names captures <date>_<time>_<commit>, and '-' is not legal in
	// a Go identifier, so the file name and the function are the capture name
	// with every non-alphanumeric character turned into an underscore.
	want := []string{
		"Code generated by cmd/gensim. DO NOT EDIT.",
		"func TestSim_" + ident(first) + "(t *testing.T)",
		`sim.Run(t, "testdata/` + first + `")`,
	}
	body, err := os.ReadFile(filepath.Join(sim, testFileName(first)))
	if err != nil {
		t.Fatal(err)
	}
	for _, w := range want {
		if !strings.Contains(string(body), w) {
			t.Errorf("the generated test is missing %q:\n%s", w, body)
		}
	}
	// The name is only usable because ident() handles it: a raw capture name
	// would not compile.
	if strings.ContainsAny(ident(first), "-.:") {
		t.Errorf("ident(%q) left characters that are illegal in an identifier: %q", first, ident(first))
	}
}

// TestRunIsIdempotent: running it twice must not report a change, because a
// generator that rewrites a file every time makes every commit that touches it
// noisy.
func TestRunIsIdempotent(t *testing.T) {
	caps := t.TempDir()
	sim := t.TempDir()
	writeCaptureDir(t, caps, "capture")
	if err := run([]string{caps}, sim, false); err != nil {
		t.Fatalf("first run: %v", err)
	}
	if err := run([]string{caps}, sim, true); err != nil {
		t.Fatalf("the second run found the committed files out of date: %v", err)
	}
}

// TestCheckFailsOnAMissingTest: -check is what CI runs, and its whole value is
// that it fails when a capture has no test.
func TestCheckFailsOnAMissingTest(t *testing.T) {
	caps := t.TempDir()
	sim := t.TempDir()
	writeCaptureDir(t, caps, "capture")
	if err := run([]string{caps}, sim, true); err == nil {
		t.Fatal("-check passed with nothing generated, so it cannot be trusted in CI")
	}
	if err := run([]string{caps}, sim, false); err != nil {
		t.Fatalf("run: %v", err)
	}
	if err := run([]string{caps}, sim, true); err != nil {
		t.Fatalf("-check failed after the files were generated: %v", err)
	}
}

// TestRunRefusesToOverwriteACommittedCapture: a capture is the record of a run
// that cannot be repeated, so a second capture with the same name and different
// bytes is a mistake to report, not to resolve by overwriting.
func TestRunRefusesToOverwriteACommittedCapture(t *testing.T) {
	caps := t.TempDir()
	sim := t.TempDir()
	writeCaptureDir(t, caps, "capture")
	if err := run([]string{caps}, sim, false); err != nil {
		t.Fatalf("first run: %v", err)
	}
	installed := filepath.Join(sim, testDataDirName, "capture", "main.log")
	if err := os.WriteFile(installed, []byte("timestamp,src_host,different\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := run([]string{caps}, sim, false); err == nil {
		t.Fatal("a capture that differs from the committed copy must be refused, not overwritten")
	}
}

// TestRunRemovesATestWhoseCaptureIsGone: a test pointing at a directory that no
// longer exists fails for a reason that has nothing to do with the server, so it
// goes when the capture does.
func TestRunRemovesATestWhoseCaptureIsGone(t *testing.T) {
	caps := t.TempDir()
	sim := t.TempDir()
	writeCaptureDir(t, caps, "capture")
	writeCaptureDir(t, caps, "gone")
	if err := run([]string{caps}, sim, false); err != nil {
		t.Fatalf("run: %v", err)
	}
	// Removed from the search path AND from testdata. Only then is its test an
	// orphan: with the copy still installed under testdata the test can still run,
	// so it is not stale.
	if err := os.RemoveAll(filepath.Join(caps, "gone")); err != nil {
		t.Fatal(err)
	}
	if err := os.RemoveAll(filepath.Join(sim, "testdata", "gone")); err != nil {
		t.Fatal(err)
	}
	if err := run([]string{caps}, sim, false); err != nil {
		t.Fatalf("run: %v", err)
	}
	if _, err := os.Stat(filepath.Join(sim, "sim_se_va_test.go")); err == nil {
		t.Error("the test of a capture that no longer exists was left behind")
	}
}

// TestRunAgainstOneRootKeepsTheOtherTests is the regression for a bug that only
// a real capture could expose. The search roots are a place to LOOK, not the
// whole world: pointing the generator at a directory holding one new capture used
// to declare every other generated test stale and delete it, taking the
// harness's own regression tests with it, silently.
func TestRunAgainstOneRootKeepsTheOtherTests(t *testing.T) {
	caps := t.TempDir()
	other := t.TempDir()
	sim := t.TempDir()
	writeCaptureDir(t, caps, "first")
	writeCaptureDir(t, other, "second")

	if err := run([]string{caps, other}, sim, false); err != nil {
		t.Fatalf("run: %v", err)
	}
	for _, name := range []string{"sim_first_test.go", "sim_second_test.go"} {
		if _, err := os.Stat(filepath.Join(sim, name)); err != nil {
			t.Fatalf("%s should exist after generating from both roots: %v", name, err)
		}
	}

	// Now only the first root. The second capture is untouched in testdata, so its
	// test must survive.
	if err := run([]string{caps}, sim, false); err != nil {
		t.Fatalf("run: %v", err)
	}
	if _, err := os.Stat(filepath.Join(sim, "sim_second_test.go")); err != nil {
		t.Error("pointing the generator at one root deleted the test of a capture that lives in another: " +
			"the search path is not the whole world")
	}
	if _, err := os.Stat(filepath.Join(sim, "testdata", "second", "metadata.json")); err != nil {
		t.Error("the capture data itself was removed too")
	}
}

// TestGeneratedFilesAreGoFormatted: the generated file is committed, and a
// committed Go file that gofmt would rewrite is a failing check in someone
// else's pipeline later.
func TestGeneratedFilesAreGoFormatted(t *testing.T) {
	caps := t.TempDir()
	sim := t.TempDir()
	writeCaptureDir(t, caps, "2026-09-28_040213_56c1309")
	if err := run([]string{caps}, sim, false); err != nil {
		t.Fatalf("run: %v", err)
	}
	entries, err := os.ReadDir(sim)
	if err != nil {
		t.Fatal(err)
	}
	for _, e := range entries {
		if !strings.HasSuffix(e.Name(), "_test.go") {
			continue
		}
		formatted, err := formatSource(filepath.Join(sim, e.Name()))
		if err != nil {
			t.Fatalf("format %s: %v", e.Name(), err)
		}
		body, err := os.ReadFile(filepath.Join(sim, e.Name()))
		if err != nil {
			t.Fatal(err)
		}
		if string(formatted) != string(body) {
			t.Errorf("%s is not gofmt'd", e.Name())
		}
	}
}
